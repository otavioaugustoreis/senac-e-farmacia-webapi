-- E-Farmácia: esquema, regras de acesso (RLS) e funções de busca

create extension if not exists postgis with schema extensions;
create extension if not exists unaccent with schema extensions;

create type public.tipo_medicamento as enum ('referencia', 'generico', 'similar');
create type public.papel as enum ('user', 'admin');

-- Perfis (1:1 com auth.users)
create table public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  nome text,
  role public.papel not null default 'user',
  criado_em timestamptz not null default now()
);

create table public.categorias (
  id bigint generated by default as identity primary key,
  nome text not null unique
);

create table public.medicamentos (
  id bigint generated by default as identity primary key,
  nome_comercial text not null check (length(trim(nome_comercial)) > 0),
  principio_ativo text not null check (length(trim(principio_ativo)) > 0),
  categoria_id bigint references public.categorias (id) on delete set null,
  tipo public.tipo_medicamento not null,
  fabricante text not null default '',
  apresentacao text not null default ''
);
create index medicamentos_categoria_idx on public.medicamentos (categoria_id);

create table public.bulas (
  medicamento_id bigint primary key references public.medicamentos (id) on delete cascade,
  para_que_serve text not null default '',
  contraindicacoes text not null default '',
  efeitos_colaterais text not null default '',
  advertencias text not null default '',
  link_anvisa text not null default 'https://consultas.anvisa.gov.br/#/bulario/'
);

create table public.farmacias (
  id bigint generated by default as identity primary key,
  nome text not null,
  endereco text not null,
  telefone text,
  parceira boolean not null default false,
  localizacao extensions.geography(Point, 4326) not null
);
create index farmacias_localizacao_idx on public.farmacias using gist (localizacao);

create table public.precos (
  id bigint generated by default as identity primary key,
  medicamento_id bigint not null references public.medicamentos (id) on delete cascade,
  farmacia_id bigint not null references public.farmacias (id) on delete cascade,
  valor numeric(10, 2) not null check (valor > 0),
  atualizado_em timestamptz not null default now(),
  unique (medicamento_id, farmacia_id)
);
create index precos_farmacia_idx on public.precos (farmacia_id);

create table public.cupons (
  id bigint generated by default as identity primary key,
  farmacia_id bigint not null references public.farmacias (id) on delete cascade,
  codigo text not null,
  descricao text not null default '',
  desconto text not null,
  validade date not null
);
create index cupons_farmacia_idx on public.cupons (farmacia_id);

create table public.reportes_preco (
  id bigint generated by default as identity primary key,
  preco_id bigint not null references public.precos (id) on delete cascade,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  comentario text not null default '' check (length(comentario) <= 500),
  criado_em timestamptz not null default now(),
  resolvido boolean not null default false
);
create index reportes_preco_idx on public.reportes_preco (preco_id);
create index reportes_user_idx on public.reportes_preco (user_id);

-- Preço alterado = data de atualização renovada
create function public.renovar_atualizado_em() returns trigger
language plpgsql set search_path = '' as $$
begin
  new.atualizado_em := now();
  return new;
end $$;

create trigger precos_atualizado_em before update on public.precos
for each row execute function public.renovar_atualizado_em();

-- Novo usuário ganha perfil comum
create function public.handle_new_user() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  insert into public.profiles (id, nome) values (new.id, new.raw_user_meta_data ->> 'nome');
  return new;
end $$;

create trigger on_auth_user_created after insert on auth.users
for each row execute function public.handle_new_user();

create function public.is_admin() returns boolean
language sql stable security definer set search_path = '' as $$
  select exists (select 1 from public.profiles where id = (select auth.uid()) and role = 'admin');
$$;

-- Views (respeitam a RLS de quem consulta)
create view public.farmacias_view with (security_invoker = true) as
select f.id, f.nome, f.endereco, f.telefone, f.parceira,
       extensions.st_y(f.localizacao::extensions.geometry) as lat,
       extensions.st_x(f.localizacao::extensions.geometry) as lng
from public.farmacias f;

create view public.reportes_view with (security_invoker = true) as
select r.id, r.preco_id, r.comentario, r.criado_em, r.resolvido,
       m.nome_comercial as medicamento, f.nome as farmacia, p.valor
from public.reportes_preco r
join public.precos p on p.id = r.preco_id
join public.medicamentos m on m.id = p.medicamento_id
join public.farmacias f on f.id = p.farmacia_id;

-- Busca por nome comercial ou princípio ativo, sem acento/maiúsculas; termo vazio = todos
create function public.buscar_medicamentos(q text default '', categoria_filtro bigint default null)
returns table (
  id bigint, nome_comercial text, principio_ativo text, tipo public.tipo_medicamento,
  categoria_id bigint, categoria text, fabricante text, apresentacao text, menor_preco numeric
)
language sql stable set search_path = '' as $$
  select m.id, m.nome_comercial, m.principio_ativo, m.tipo, m.categoria_id, c.nome,
         m.fabricante, m.apresentacao,
         (select min(p.valor) from public.precos p where p.medicamento_id = m.id)
  from public.medicamentos m
  left join public.categorias c on c.id = m.categoria_id
  where (coalesce(trim(q), '') = ''
         or extensions.unaccent(m.nome_comercial) ilike '%' || extensions.unaccent(trim(q)) || '%'
         or extensions.unaccent(m.principio_ativo) ilike '%' || extensions.unaccent(trim(q)) || '%')
    and (categoria_filtro is null or m.categoria_id = categoria_filtro)
  order by m.nome_comercial;
$$;

-- Farmácias dentro do raio, da mais próxima para a mais distante
create function public.farmacias_proximas(origem_lat float8, origem_lng float8, raio_km float8 default 15)
returns table (
  id bigint, nome text, endereco text, telefone text, parceira boolean,
  lat float8, lng float8, distancia_km float8
)
language sql stable set search_path = '' as $$
  with origem as (
    select extensions.st_setsrid(extensions.st_makepoint(origem_lng, origem_lat), 4326)::extensions.geography as ponto
  )
  select f.id, f.nome, f.endereco, f.telefone, f.parceira,
         extensions.st_y(f.localizacao::extensions.geometry),
         extensions.st_x(f.localizacao::extensions.geometry),
         extensions.st_distance(f.localizacao, o.ponto) / 1000.0
  from public.farmacias f, origem o
  where extensions.st_dwithin(f.localizacao, o.ponto, raio_km * 1000.0)
  order by 8;
$$;

-- RLS
alter table public.profiles enable row level security;
alter table public.categorias enable row level security;
alter table public.medicamentos enable row level security;
alter table public.bulas enable row level security;
alter table public.farmacias enable row level security;
alter table public.precos enable row level security;
alter table public.cupons enable row level security;
alter table public.reportes_preco enable row level security;

create policy "perfil: dono ou admin lê" on public.profiles
  for select to authenticated using (id = (select auth.uid()) or (select public.is_admin()));

do $$
declare t text;
begin
  foreach t in array array['categorias', 'medicamentos', 'bulas', 'farmacias', 'precos', 'cupons'] loop
    execute format('create policy "catálogo: leitura pública" on public.%I for select to anon, authenticated using (true)', t);
    execute format('create policy "catálogo: admin insere" on public.%I for insert to authenticated with check ((select public.is_admin()))', t);
    execute format('create policy "catálogo: admin altera" on public.%I for update to authenticated using ((select public.is_admin())) with check ((select public.is_admin()))', t);
    execute format('create policy "catálogo: admin exclui" on public.%I for delete to authenticated using ((select public.is_admin()))', t);
  end loop;
end $$;

create policy "reporte: usuário logado cria o próprio" on public.reportes_preco
  for insert to authenticated with check (user_id = (select auth.uid()));
create policy "reporte: admin lê" on public.reportes_preco
  for select to authenticated using ((select public.is_admin()));
create policy "reporte: admin altera" on public.reportes_preco
  for update to authenticated using ((select public.is_admin())) with check ((select public.is_admin()));
create policy "reporte: admin exclui" on public.reportes_preco
  for delete to authenticated using ((select public.is_admin()));

-- Ninguém altera o próprio papel pelo cliente
revoke insert, update, delete on public.profiles from anon, authenticated;
